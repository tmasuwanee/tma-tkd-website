/**
 * Builds the assistant's playbook/SOP corpus from the source docs into a bundled
 * TypeScript module (server/playbook-corpus.ts). Baking the text into code means
 * the server never depends on doc file paths existing at runtime.
 *
 * FRESHNESS: re-run this whenever the SOP or playbook changes:
 *   node scripts/build-playbook-corpus.mjs
 * then commit the regenerated server/playbook-corpus.ts.
 *
 * (Embeddings are computed at runtime by server/playbook-rag.ts and cached, so we
 * only bake the text here, not vectors — no OpenAI key needed to build.)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const chunks = [];

// ── docs/FRONT_DESK_SOP.md — split on "## " headings ──
const sopPath = resolve(root, "docs/FRONT_DESK_SOP.md");
if (existsSync(sopPath)) {
  const md = readFileSync(sopPath, "utf8");
  const parts = md.split(/\n(?=## )/);
  for (const part of parts) {
    const text = part.trim();
    if (text.length < 40) continue;
    const titleMatch = text.match(/^#{1,3}\s+(.+)/);
    const title = titleMatch ? titleMatch[1].trim() : "Front Desk SOP";
    chunks.push({ source: "Front Desk SOP", title, text });
  }
}

// ── client/public/playbook.html — strip to text, chunk by size ──
const pbPath = resolve(root, "client/public/playbook.html");
if (existsSync(pbPath)) {
  let html = readFileSync(pbPath, "utf8");
  html = html.replace(/<style[\s\S]*?<\/style>/gi, " ").replace(/<script[\s\S]*?<\/script>/gi, " ");
  const text = html
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&nbsp;/g, " ").replace(/&mdash;/g, "-").replace(/&rarr;/g, "->").replace(/&#\d+;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  // ~900-char windows on sentence-ish boundaries
  const size = 900;
  for (let i = 0; i < text.length; i += size) {
    const slice = text.slice(i, i + size).trim();
    if (slice.length < 60) continue;
    chunks.push({ source: "Front Desk Playbook", title: "Where things live", text: slice });
  }
}

const out = `// GENERATED by scripts/build-playbook-corpus.mjs — do not edit by hand.
// Re-run that script after changing the SOP or playbook, then commit this file.
export type PlaybookChunk = { source: string; title: string; text: string };
export const PLAYBOOK_CORPUS: PlaybookChunk[] = ${JSON.stringify(chunks, null, 2)};
`;
writeFileSync(resolve(root, "server/playbook-corpus.ts"), out, "utf8");
console.log(`Wrote server/playbook-corpus.ts with ${chunks.length} chunks.`);
